// Turns the built style sheet into one self-contained HTML file that opens without a server.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const html = readFileSync('dist/styleguide.html', 'utf8');
const asset = (url) => readFileSync(url.replace(/^\/strable\//, 'dist/'), 'utf8');

const standalone = html
  .replace('<!doctype html>', '<!doctype html>\n<!-- Generated by `npm run snapshot`. Do not edit by hand. -->')
  .replace(
    /<script type="module" crossorigin src="([^"]+)"><\/script>/,
    (_, src) => `<script type="module">\n${asset(src)}</script>`,
  )
  .replace(/<link rel="stylesheet" crossorigin href="([^"]+)">/, (_, href) => `<style>\n${asset(href)}</style>`);

if (standalone.includes('/strable/assets/')) throw new Error('Some assets were not inlined');

mkdirSync('docs', { recursive: true });
writeFileSync('docs/styleguide.html', standalone);
console.log(`docs/styleguide.html (${(standalone.length / 1024).toFixed(1)} kB)`);
